"""Merge the two highlight.js themes into one stylesheet.

The viewer switches theme by setting data-theme on <html>. Shipping two
stylesheets meant enabling one and disabling the other from JavaScript, which
only happens after the first paint - code blocks flashed in the wrong colours
on every start. One file whose dark rules are scoped to [data-theme="dark"]
removes both the flash and the JavaScript.

Inputs are the upstream minified themes (GitHub / GitHub Dark) from
highlight.js, kept verbatim in tools/hljs-themes/. They contain no at-rules,
so a plain rule-level rewrite is enough.

    python tools/make_hljs_css.py
"""

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SOURCES = HERE / "hljs-themes"
ASSETS = HERE.parent / "assets"
DARK_SCOPE = '[data-theme="dark"] '

COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
RULE = re.compile(r"([^{}]+)\{([^{}]*)\}", re.DOTALL)

# The upstream themes also style the code block itself - padding, surface and base
# text colour. viewer.css already owns those, and the theme's versions are more
# specific than ours, so they would quietly win and paint dark code blocks in the
# page background colour. Only the token colours are kept.
BASE_SELECTORS = {".hljs", "code.hljs", "pre code.hljs"}


def rules(css: str) -> str:
    """Normalise a minified stylesheet to one token-colour rule per line."""
    css = COMMENT.sub("", css)
    out = []
    for selectors, body in RULE.findall(css):
        kept = [s.strip() for s in selectors.split(",") if s.strip() not in BASE_SELECTORS]
        body = body.strip()
        if kept and body:
            out.append(f"{','.join(kept)}{{{body}}}")
    return "\n".join(out)


def scoped(css: str, scope: str) -> str:
    """Prefix every selector so the rule only applies inside `scope`."""
    out = []
    for line in rules(css).splitlines():
        selectors, body = line.split("{", 1)
        selectors = ",".join(scope + s for s in selectors.split(","))
        out.append(f"{selectors}{{{body}")
    return "\n".join(out)


def main() -> None:
    light = (SOURCES / "hljs-light.css").read_text(encoding="utf-8")
    dark = (SOURCES / "hljs-dark.css").read_text(encoding="utf-8")

    merged = "\n".join([
        "/* highlight.js themes: GitHub (light) and GitHub Dark.",
        "   BSD-3-Clause, (c) 2006-2024 highlight.js contributors.",
        "   Generated by tools/make_hljs_css.py - do not edit by hand. */",
        rules(light),
        scoped(dark, DARK_SCOPE),
        "",
    ])

    target = ASSETS / "hljs.css"
    target.write_text(merged, encoding="utf-8")
    print(f"Wrote {target} ({len(merged.encode('utf-8')) / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
